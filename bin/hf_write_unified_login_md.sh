#!/usr/bin/env bash
set -euo pipefail

ROOT="/root/HyperFFactory"

if [[ ! -d "$ROOT" ]]; then
  echo "❌ الجذر $ROOT غير موجود – هذا السكربت يفترض الهيكل الموحّد."
  exit 1
fi

cd "$ROOT"

# تأكيد وجود opt/ داخل الهيكل الموحّد
mkdir -p "$ROOT/opt"

# تجهيز docs/
mkdir -p docs

TARGET_MD="docs/UNIFIED_FACTORY_LOGIN.md"

cat > "$TARGET_MD" <<'DOC'
========================================================
        HyperFFactory – Unified Factory Login
========================================================

# HyperFFactory – المصنع الموحّد الرسمي

## 1. تعريف مختصر

HyperFFactory هو المصنع الموحّد لتجميع وتشغيل الأنظمة التالية على السيرفر:

- SmartFriend Suite (هوية، ذاكرة، بوتات، Web/Gateway)
- FFactory / AI Stack (خدمات الذكاء الاصطناعي والدعم)
- سكربتات الفحص، الإصلاح، النسخ الاحتياطي، والتشغيل الآلي

> جميع الريبوهاِت على GitHub تستخدم للاستدلال والتوثيق فقط.  
> التشغيل الفعلي والاعتماد الإنتاجي على السيرفر داخل الهيكل الموحّد.

## 2. مواقع التنفيذ الرسمية

- المصنع الموحّد (Orchestrator):
  - `/root/HyperFFactory`

- أنظمة متكاملة تحت سيطرته:
  - `/opt/smartfriend-suite`  ← نظام SmartFriend Suite
  - `/opt/ffactory`          ← نظام FFactory / AI Stack (Stack مستقل متكامل)

أي تشغيل أو سكربت خارج هذه البنية يعتبر مخالفة لسياسة الهيكل الموحّد ويجب إصلاحه.

## 3. دور الريبوهاِت (للاستدلال فقط)

- `HyperFFactory`          ← التصميم والهوية للمصنع الموحّد.
- `hyper-factory`          ← مرجع لخط إنتاج بيانات بسيط (inbox → raw → processed → …).
- `ffactory` / `ffactory2` ← مراجع بنية الـ AI Stack (Postgres, Ollama, ASR, …).
- `smartfriend-suite`      ← كود SmartFriend المنتج (apps/gateway/bots/…).
- `smartfrind`             ← نسخة Legacy قديمة (غير معتمدة للإنتاج).
- `other`                  ← سكربتات وأرشيف وتاريخ تجارب.

## 4. خريطة العمل الموحدة (Roadmap عالية المستوى)

### المرحلة 1 – التوحيد الأساسي

- توحيد مسارات التنفيذ تحت:
  - `/root/HyperFFactory`
  - `/opt/smartfriend-suite`
  - `/opt/ffactory` كنظام خارجي.
- تجميع سكربتات وتشخيصات الأنظمة داخل:
  - `HyperFFactory/imported/`
  - `HyperFFactory/reports/`
- إنشاء مركز صحّة موحّد (Unified Health Center).

### المرحلة 2 – الدمج والتكامل

- قناة تكامل رسمية بين HyperFFactory و SmartFriend (Health / Memory / Knowledge / Gateway).
- قناة تكامل رسمية بين HyperFFactory و FFactory (AI / ASR / Tools).
- توحيد مسارات النسخ الاحتياطي والسياسات التشغيلية.

### المرحلة 3 – التحسين والجودة

- تعريف مؤشرات أداء (KPIs) وتشغيل فحوصات دورية.
- لوحات تحكم موحّدة (CLI / Telegram / Web).
- تحسين الأداء، الأمان، والاختبارات المستمرة.

## 5. سياسة التشغيل

1) التنفيذ من داخل الهيكل الموحّد فقط.  
2) عدم المساس بمشروع FFactory المنتج (Stack مستقل، دمج فقط).  
3) عدم حذف أي قاعدة بيانات أو تقارير تشخيص أو أرشيف.  
4) GitHub للمرجع فقط، السيرفر هو مصدر الحقيقة الوحيد.

## 6. سياسة الهيكل الموحّد الصارمة (Unified Tree Strict Policy)

هذه السياسة مُلزِمة لكل سكربت/خدمة/نموذج يعمل تحت HyperFFactory:

1. الهيكل المرجعي:
   - `/root/HyperFFactory` هو الجذر الوحيد للمصنع الموحّد.
   - مجلد `opt/` داخله (`/root/HyperFFactory/opt`) جزء من الهيكل الموحّد،  
     وليس بديلاً عن `/opt` الخاص بالنظام.

2. ممنوع إنشاء ملفات/مجلدات تشغيلية خارج الهيكل:
   - يُمنع على أي سكربت تابع لـ HyperFFactory أن ينشئ ملفات تشغيل أو تقارير
     خارج `/root/HyperFFactory` إلا في حالات تكامل موثّقة (مثل `/opt/smartfriend-suite` و `/opt/ffactory`).

3. منع symlink/hardlink إلى خارج الهيكل:
   - يُمنع استخدام symlink أو hardlink داخل `/root/HyperFFactory`
     لتوجيه التنفيذ إلى مسارات خارج الهيكل (مثل `/`, `/usr`, `/var`…).
   - الاستثناء الوحيد: روابط تكامل موثّقة إلى:
     - `/opt/smartfriend-suite`
     - `/opt/ffactory`

4. أنظمة خارجية متكاملة (Integration Systems):
   - `/opt/smartfriend-suite` و `/opt/ffactory` تُعامل كنُظم متكاملة مستقلة،
     يتم الوصول لها عبر واجهات تكامل (API / Services / Health) وليس عبر خلط ملفاتها
     داخل هيكل HyperFFactory.

5. رصد المخالفات:
   - أي سكربت يكتشف:
     - ملفات تم إنشاؤها خارج الهيكل،
     - أو symlink/hardlink مشبوه داخل الهيكل،
     يجب أن يسجّل المخالفة في:
     - `reports/unified_tree_violations.log`
     - ويدخل سجلًا في قاعدة:
     - `db/meta/hf_changes.db`

6. توثيق أي توسّع:
   - أي إضافة لمسارات جديدة داخل الهيكل الموحّد
     يجب أن تُوثَّق أولاً هنا في هذا الملف قبل استخدامها إنتاجيًا.

7. الهدف من هذه السياسة:
   - ضمان أن يكون المصنع “هيكل واحد كامل متكامل”.
   - منع النماذج/السكربتات المستقبلية من خلق مسارات عشوائية.
   - ضمان قدرة الحوكمة على تتبع كل تغيير في المسارات.

## 7. إلزام تسجيل التقدّم والمسارات والاقتراحات

8. **ضرورة تسجيل التقدّم والملفات والمسارات واقتراح الحالة الحالية في الخطة**:

- أي سكربت أو نموذج يعمل تحت HyperFFactory مُلزَم بأن يقوم بـ:

1) تسجيل التقدّم (Progress Logging):
   - كتابة ما حدث في:
     - `reports/` أو `logs/`
   - يشمل:
     - وقت التنفيذ
     - ما تم فحصه أو تعديله
     - النتيجة (نجاح/فشل جزئي/فشل)

2) تسجيل الملفات والمسارات (File & Path Tracking):
   - لكل تعديل ملف مهم (config, service, db, scripts):
     - اسم الملف
     - المسار الكامل
     - نوع العملية (إنشاء/تعديل/نقل)
     - السكربت المنفّذ
   - تُسجّل كـ حدث في:
     - `db/meta/hf_changes.db`

3) تسجيل اقتراح الحالة التالية في الخطة (Plan-Aware Suggestions):
   - بعد كل عملية مهمّة (فحص، إصلاح، نقل كبير):
     - يُسجَّل اقتراح واضح:
       - ما هي الخطوة التالية؟
       - هل تؤثر على SmartFriend أو FFactory أو HyperFFactory نفسه؟
     - تُكتب في:
       - `reports/next_steps/…`
       - مع ملخّص في `plan_status.md` عند الحاجة.

4) لا يُعتبر أي إنجاز “مكتمل” بدون سجل:
   - أي خطوة تُنفَّذ بدون تسجيل التقدّم والملفات والمسارات
     تعتبر مخالفة مباشرة لسياسة المصنع الموحّد.

DOC

echo "✅ تم إنشاء/تحديث $TARGET_MD (ملف الهوية والسياسة الموحد)."
